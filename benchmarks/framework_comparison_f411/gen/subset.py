"""Cut a generated <model>_data.h down to its first N test samples, for boards
whose flash cannot hold the whole test set (the NUCLEO-L031K6 has 32 KB).
Every array in the file is laid out sample-major, so each keeps the leading
size * N / N_TEST elements, and <MODEL>_N_TEST becomes N. The model-level
hash/accuracy defines describe the full set and are dropped; the expected
tinymind hash for a prefix lives in fw/backend.hpp.

  python3 -I gen/subset.py <in.h> <out.h> <N>
"""

import re
import sys


def main():
    src, dst, n = sys.argv[1], sys.argv[2], int(sys.argv[3])
    text = open(src).read()

    m = re.search(r"#define (\w+)_N_TEST (\d+)\n", text)
    prefix, total = m.group(1), int(m.group(2))
    if not 0 < n <= total:
        sys.exit("N must be in 1..%d" % total)
    text = text.replace(m.group(0), "#define %s_N_TEST %d\n#define %s_N_TEST_FULL %d\n" % (prefix, n, prefix, total))
    text = re.sub(r"#define %s_INT8_(HASH|ACC_X10000) \w+\n" % prefix, "", text)

    def cut(a):
        size = int(a.group(2))
        if size % total:
            sys.exit("%s[%d] is not sample-major over %d samples" % (a.group(1), size, total))
        keep = size // total * n
        values = [v for v in re.split(r"[\s,]+", a.group(3)) if v]
        if len(values) != size:
            sys.exit("%s: expected %d values, found %d" % (a.group(1), size, len(values)))
        per_line = 16
        body = "".join("    " + ", ".join(values[i:i + per_line]) + ",\n" for i in range(0, keep, per_line))
        return "%s[%d] =\n{\n%s};" % (a.group(1), keep, body)

    text = re.sub(r"(\w[\w ()]*?\w)\[(\d+)\] =\n\{\n(.*?)\};", cut, text, flags=re.S)
    text = text.replace("// Generated by gen/make_models.py -- do not edit.",
                        "// Generated by gen/subset.py from gen/out (first %d of %d samples) -- do not edit." % (n, total))
    open(dst, "w").write(text)


if __name__ == "__main__":
    main()
