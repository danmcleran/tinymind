"""Translate the MLPerf Tiny reference int8 models into tinymind layers.

Downloads the keyword spotting (DS-CNN) and image classification (ResNet-8)
reference models from github.com/mlcommons/tiny at a pinned commit, checks
their SHA-256, and writes into gen/mlperf/ (gitignored):

  mlperf_<m>_tinymind.hpp   the graph as tinymind layers over one planned arena
  mlperf_<m>_tflite_int8.h  the unmodified flatbuffer, for the TFLM images
  mlperf_<m>_data.h         seeded random int8 test inputs

The models are Apache-2.0 (MLCommons), so neither they nor anything derived
from their weights is committed here; `make mlperf-models` regenerates them.
The test inputs are random, not dataset samples: the benchmark measures
latency, memory and bit-exactness with TFLM, not accuracy, and the reference
models' accuracy is MLCommons' to report.

Every layer reuses the model's own int8 weights, int32 biases and the
requantizer multipliers TFLM derives from its scales, so tinymind and TFLM
run the same integer arithmetic and must agree bit for bit. SAME padding,
is folded into the convolution and depthwise layers (their PadTop..PadRight
parameters), which pad with the input zero point as TFLM's kernels do. A
layer whose padded-row band would exceed TINYMIND_CONV_PAD_BAND_MAX_BYTES
gets an explicit QPad2D pass instead.

Requires the benchmark venv (tensorflow-cpu, numpy).
"""

import hashlib
import math
import os
import sys
import urllib.request

import numpy as np

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
import tensorflow as tf  # noqa: E402
from tensorflow.lite.python import schema_py_generated as schema  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "mlperf")
CACHE = os.path.join(OUT, "cache")

MLPERF_TINY_COMMIT = "4addd0fa08d216e20637637874e084895f289da4"
MODELS = {
    "kws": ("benchmark/training/keyword_spotting/trained_models/kws_ref_model.tflite",
            "aeea436800704fce17b17292e4412630ad856e9d777c044c64ef748a880bd0ae"),
    "ic": ("benchmark/training/image_classification/trained_models/pretrainedResnet_quant.tflite",
           "3c002613d1b2475eb51dd78dfb85a546c8ae658dee71cf6ade43b022fe205415"),
}
N_TEST = 8
PAD_BAND_MAX_BYTES = 4096  # TINYMIND_CONV_PAD_BAND_MAX_BYTES default
HDR = ("// Generated by gen/make_mlperf.py -- do not edit, do not commit.\n"
       "// Derived from an MLPerf Tiny reference model (github.com/mlcommons/tiny,\n"
       f"// commit {MLPERF_TINY_COMMIT}), Apache License 2.0, Copyright MLCommons.\n")

# ---------------------------------------------------------------- helpers


def fetch(name):
    path, sha = MODELS[name]
    os.makedirs(CACHE, exist_ok=True)
    local = os.path.join(CACHE, os.path.basename(path))
    if not os.path.exists(local):
        url = f"https://raw.githubusercontent.com/mlcommons/tiny/{MLPERF_TINY_COMMIT}/{path}"
        print("fetching", url)
        with urllib.request.urlopen(url, timeout=60) as r:
            data = r.read()
        with open(local + ".part", "wb") as f:
            f.write(data)
        os.replace(local + ".part", local)
    blob = open(local, "rb").read()
    got = hashlib.sha256(blob).hexdigest()
    if got != sha:
        sys.exit(f"{local}: sha256 {got}, expected {sha}; delete it and rerun")
    return blob


def c_array(ctype, name, values, per_line=16, align=None):
    vals = [int(v) for v in np.asarray(values).ravel()]
    lines = ["    " + ", ".join(str(v) for v in vals[i:i + per_line]) + ","
             for i in range(0, len(vals), per_line)]
    a = f"alignas({align}) " if align else ""
    return f"{a}const {ctype} {name}[{len(vals)}] =\n{{\n" + "\n".join(lines) + "\n};\n"


def fnv1a(data):
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def quantize_multiplier(m):
    """TFLite QuantizeMultiplier: m = q * 2^(shift - 31), shift > 0 = left."""
    if m == 0.0:
        return 0, 0
    frac, exp = math.frexp(m)
    q = int(round(frac * (1 << 31)))
    if q == (1 << 31):
        q //= 2
        exp += 1
    if exp < -31:
        return 0, 0
    return q, exp


def f64(x):
    return float(np.float64(np.float32(x)))


def act_range(act, scale, zp):
    """TFLite CalculateActivationRangeQuantized for int8."""
    qmin, qmax = -128, 127
    if act == schema.ActivationFunctionType.RELU:
        qmin = max(qmin, zp)
    elif act == schema.ActivationFunctionType.RELU6:
        qmin = max(qmin, zp)
        qmax = min(qmax, zp + int(round(6.0 / f64(scale))))
    elif act != schema.ActivationFunctionType.NONE:
        raise ValueError(f"unsupported fused activation {act}")
    return qmin, qmax


def rq(in_scale, w_scale, out_scale, out_zp, qmin, qmax):
    # Conv/FC effective scale as TFLM computes it: in double from float scales.
    mult, shift = quantize_multiplier(f64(in_scale) * f64(w_scale) / f64(out_scale))
    # tinymind Requantizer: shift > 0 means right shift (opposite of TFLite).
    return "{%d, %d, %d, %d, %d}" % (mult, -shift, out_zp, qmin, qmax)


def same_pads(in_size, k, stride):
    out = (in_size + stride - 1) // stride
    total = max((out - 1) * stride + k - in_size, 0)
    return total // 2, total - total // 2, out


# ---------------------------------------------------------------- translation


class Graph:
    """Walks the TFLite ops and emits tinymind layers plus a step list."""

    def __init__(self, name, blob):
        self.ns = f"tm_mlperf_{name}"
        self.it = tf.lite.Interpreter(
            model_content=blob,
            experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_REF)
        self.it.allocate_tensors()
        self.model = schema.Model.GetRootAsModel(blob, 0)
        self.sub = self.model.Subgraphs(0)
        self.T = {t["index"]: t for t in self.it.get_tensor_details()}
        self.decls = []
        self.steps = []      # (tag, layer, [input buffers], output buffer)
        self.buffers = {}    # buffer name -> bytes
        self.alias = {}      # tensor index -> buffer name
        self.n = 0
        inp = self.it.get_input_details()[0]
        outp = self.it.get_output_details()[0]
        self.in_index, self.out_index = inp["index"], outp["index"]
        self.alias[self.in_index] = "in"
        self.n_in = int(np.prod(inp["shape"]))
        self.n_out = int(np.prod(outp["shape"]))

    def qp(self, idx):
        q = self.T[idx]["quantization_parameters"]
        return np.asarray(q["scales"], np.float32), np.asarray(q["zero_points"], np.int64)

    def shape(self, idx):
        return [int(v) for v in self.T[idx]["shape"]]

    def tensor(self, idx):
        return self.it.get_tensor(idx)

    def buf(self, idx):
        if idx == self.out_index:
            return "out"
        if idx not in self.alias:
            name = f"t{idx}"
            self.buffers[name] = int(np.prod(self.shape(idx)))
            self.alias[idx] = name
        return self.alias[idx]

    def scratch(self, nbytes):
        name = f"s{len(self.buffers)}"
        self.buffers[name] = nbytes
        return name

    def options(self, k, cls):
        o = self.sub.Operators(k).BuiltinOptions()
        x = cls()
        x.Init(o.Bytes, o.Pos)
        return x

    def rqs_decl(self, var, rqs):
        self.decls.append(f"const Rq {var}[{len(rqs)}] = {{" + ", ".join(rqs) + "};\n")

    def conv(self, k, op, depthwise):
        x, w, b = op["inputs"][:3]
        y = op["outputs"][0]
        o = self.options(k, schema.DepthwiseConv2DOptions if depthwise else schema.Conv2DOptions)
        if o.DilationHFactor() != 1 or o.DilationWFactor() != 1:
            raise ValueError("dilated convolution is not supported")
        _, H, W, C = self.shape(x)
        _, OH, OW, F = self.shape(y)
        W8 = self.tensor(w)
        B32 = self.tensor(b)
        s_in, z_in = self.qp(x)
        s_w, _ = self.qp(w)
        s_out, z_out = self.qp(y)
        z_in, z_out = int(z_in[0]), int(z_out[0])
        qmin, qmax = act_range(o.FusedActivationFunction(), s_out[0], z_out)
        sh, sw = o.StrideH(), o.StrideW()
        if depthwise:
            assert o.DepthMultiplier() == 1 and W8.shape[0] == 1
            KH, KW = W8.shape[1], W8.shape[2]
        else:
            KH, KW = W8.shape[1], W8.shape[2]
        if len(s_w) == 1:
            s_w = np.repeat(s_w, F)
        rqs = [rq(s_in[0], s, s_out[0], z_out, qmin, qmax) for s in s_w]

        i = self.n
        self.n += 1
        tag = ("dw" if depthwise else ("pw" if KH == KW == 1 else "conv")) + str(i)
        src = self.buf(x)
        if o.Padding() == schema.Padding.SAME:
            pt, pb, oh = same_pads(H, KH, sh)
            pl, pr, ow = same_pads(W, KW, sw)
            assert (oh, ow) == (OH, OW)
        else:
            pt = pb = pl = pr = 0
        band = KH * (W + pl + pr) * (1 if depthwise else C)
        pads = ""
        if (pt or pb or pl or pr) and band <= PAD_BAND_MAX_BYTES:
            pads = f", {pt}, {pb}, {pl}, {pr}"
        elif pt or pb or pl or pr:
            PH, PW = H + pt + pb, W + pl + pr
            self.decls.append(
                f"using Pad{i}Type = tinymind::QPad2D<int8_t, {H}, {W}, {C}, {pt}, {pb}, {pl}, {pr}>;\n"
                f"const Pad{i}Type Pad{i} = {{{z_in}}};\n")
            padded = self.scratch(PH * PW * C)
            self.steps.append((tag + "_pad", f"Pad{i}", [src], padded))
            src, H, W = padded, PH, PW

        if depthwise:
            Wt = np.transpose(W8[0], (2, 0, 1))  # [KH][KW][C] -> [C][KH][KW]
            self.decls.append(c_array("int8_t", f"W{i}", Wt, align=4) + c_array("int32_t", f"B{i}", B32))
            self.rqs_decl(f"R{i}", rqs)
            self.decls.append(
                f"using L{i}Type = tinymind::QDepthwiseConv2D<int8_t, int8_t, int32_t, int8_t, "
                f"{H}, {W}, {C}, {KH}, {KW}, {sh}, {sw}{pads}>;\n")
        else:
            self.decls.append(c_array("int8_t", f"W{i}", W8, align=4) + c_array("int32_t", f"B{i}", B32))
            self.rqs_decl(f"R{i}", rqs)
            if KH == KW == 1 and sh == sw == 1:
                self.decls.append(
                    f"using L{i}Type = tinymind::QPointwiseConv2DPerChannel<int8_t, int8_t, int32_t, int8_t, "
                    f"{H}, {W}, {C}, {F}>;\n")
            else:
                self.decls.append(
                    f"using L{i}Type = tinymind::QConv2DPerChannel<int8_t, int8_t, int32_t, int8_t, "
                    f"{H}, {W}, {C}, {KH}, {KW}, {sh}, {sw}, {F}{pads}>;\n")
        self.decls.append(f"const L{i}Type L{i} = {{W{i}, B{i}, {z_in}, R{i}}};\n")
        self.decls.append(f"static_assert(L{i}Type::OutputSize == {OH * OW * F}, \"L{i} output shape\");\n\n")
        self.steps.append((tag, f"L{i}", [src], self.buf(y)))

    def avgpool(self, k, op):
        x, y = op["inputs"][0], op["outputs"][0]
        o = self.options(k, schema.Pool2DOptions)
        _, H, W, C = self.shape(x)
        if not (o.FilterHeight() == H and o.FilterWidth() == W and o.Padding() == schema.Padding.VALID):
            raise ValueError("only a global average pool is supported")
        s_in, z_in = self.qp(x)
        s_out, z_out = self.qp(y)
        assert np.isclose(s_in[0], s_out[0]) and z_in[0] == z_out[0], "avgpool requantizes"
        qmin, qmax = act_range(o.FusedActivationFunction(), s_out[0], int(z_out[0]))
        i = self.n
        self.n += 1
        self.decls.append(f"using L{i}Type = tinymind::QGlobalAvgPool2D<int8_t, int32_t, {H}, {W}, {C}>;\n"
                          f"const L{i}Type L{i} = {{{qmin}, {qmax}}};\n\n")
        self.steps.append((f"avgpool{i}", f"L{i}", [self.buf(x)], self.buf(y)))

    def fully_connected(self, k, op):
        x, w, b = op["inputs"][:3]
        y = op["outputs"][0]
        o = self.options(k, schema.FullyConnectedOptions)
        W8 = self.tensor(w)
        n_out, n_in = W8.shape
        s_in, z_in = self.qp(x)
        s_w, _ = self.qp(w)
        s_out, z_out = self.qp(y)
        assert len(s_w) == 1, "per-channel fully connected"
        qmin, qmax = act_range(o.FusedActivationFunction(), s_out[0], int(z_out[0]))
        i = self.n
        self.n += 1
        self.decls.append(c_array("int8_t", f"W{i}", W8, align=4) + c_array("int32_t", f"B{i}", self.tensor(b)))
        self.decls.append(
            f"using L{i}Type = tinymind::QDense<int8_t, int8_t, int32_t, int8_t, {n_in}, {n_out}>;\n"
            f"const L{i}Type L{i} = {{W{i}, B{i}, {int(z_in[0])}, "
            f"{rq(s_in[0], s_w[0], s_out[0], int(z_out[0]), qmin, qmax)}}};\n\n")
        self.steps.append((f"fc{i}", f"L{i}", [self.buf(x)], self.buf(y)))

    def softmax(self, k, op):
        x, y = op["inputs"][0], op["outputs"][0]
        beta = self.options(k, schema.SoftmaxOptions).Beta()
        s_in, _ = self.qp(x)
        s_out, z_out = self.qp(y)
        assert np.float32(s_out[0]) == np.float32(1.0 / 256) and z_out[0] == -128
        # TFLM PreprocessSoftmaxScaling (5 integer bits) and CalculateInputRadius.
        real = min(f64(beta) * f64(s_in[0]) * (1 << 26), (1 << 31) - 1.0)
        mult, left = quantize_multiplier(real)
        assert left >= 0
        diff_min = -int(math.floor(31.0 * (1 << 26) / (1 << left)))
        shp = self.shape(x)
        i = self.n
        self.n += 1
        self.decls.append(
            f"using L{i}Type = tinymind::QSoftmaxFixedPoint1D<{int(np.prod(shp[:-1]))}, {shp[-1]}>;\n"
            f"const L{i}Type L{i} = {{{mult}, {left}, {diff_min}}};\n\n")
        self.steps.append((f"softmax{i}", f"L{i}", [self.buf(x)], self.buf(y)))

    def add(self, k, op):
        a, b = op["inputs"][:2]
        y = op["outputs"][0]
        o = self.options(k, schema.AddOptions)
        assert self.shape(a) == self.shape(b) == self.shape(y), "broadcasting ADD"
        sa, za = self.qp(a)
        sb, zb = self.qp(b)
        so, zo = self.qp(y)
        # TFLM add.cc: left shift 20, twice the larger input scale (in float).
        twice_max = f64(np.float32(2) * max(np.float32(sa[0]), np.float32(sb[0])))
        ma, ea = quantize_multiplier(f64(sa[0]) / twice_max)
        mb, eb = quantize_multiplier(f64(sb[0]) / twice_max)
        mo, eo = quantize_multiplier(twice_max / f64(np.float32((1 << 20) * np.float32(so[0]))))
        qmin, qmax = act_range(o.FusedActivationFunction(), so[0], int(zo[0]))
        i = self.n
        self.n += 1
        n = int(np.prod(self.shape(y)))
        self.decls.append(
            f"using L{i}Type = tinymind::QAdd<int8_t, int8_t, int8_t, {n}>;\n"
            f"const L{i}Type L{i} = {{{int(za[0])}, {int(zb[0])}, 20, {ma}, {-ea}, {mb}, {-eb}, "
            f"{{{mo}, {-eo}, {int(zo[0])}, {qmin}, {qmax}}}}};\n\n")
        self.steps.append((f"add{i}", f"L{i}", [self.buf(a), self.buf(b)], self.buf(y)))

    def translate(self):
        names = []
        for k, op in enumerate(self.it._get_ops_details()):
            name = op["op_name"]
            names.append(name)
            if name == "CONV_2D":
                self.conv(k, op, depthwise=False)
            elif name == "DEPTHWISE_CONV_2D":
                self.conv(k, op, depthwise=True)
            elif name == "AVERAGE_POOL_2D":
                self.avgpool(k, op)
            elif name == "FULLY_CONNECTED":
                self.fully_connected(k, op)
            elif name == "SOFTMAX":
                self.softmax(k, op)
            elif name == "ADD":
                self.add(k, op)
            elif name == "RESHAPE":
                x, y = op["inputs"][0], op["outputs"][0]
                if y == self.out_index:
                    raise ValueError("graph ends in RESHAPE")
                self.alias[y] = self.buf(x)
            else:
                raise ValueError(f"unsupported op {name}")
        return names

    def plan(self):
        """Greedy by size, first fit by offset, over step lifetimes (as TFLM's planner)."""
        first, last = {}, {}
        for s, (_, _, ins, out) in enumerate(self.steps):
            for b in ins + [out]:
                if b in self.buffers:
                    first.setdefault(b, s)
                    last[b] = s
        placed = []  # (offset, size, first, last)
        offsets = {}
        for b in sorted(self.buffers, key=lambda b: (-self.buffers[b], first[b])):
            size = (self.buffers[b] + 3) & ~3
            off = 0
            for o, sz, f, l in sorted(p for p in placed if not (p[3] < first[b] or p[2] > last[b])):
                if off + size <= o:
                    break
                off = max(off, o + sz)
            offsets[b] = off
            placed.append((off, size, first[b], last[b]))
        arena = max(o + sz for o, sz, _, _ in placed)
        return offsets, arena

    def header(self):
        offsets, arena = self.plan()

        def ref(b):
            return b if b in ("in", "out") else f"a + {offsets[b]}"

        calls = "\n".join(f"    step(\"{tag}\", {layer}, " + ", ".join(ref(b) for b in ins) + f", {ref(out)});"
                          for tag, layer, ins, out in self.steps)
        return (HDR + "#pragma once\n#include <cstdint>\n"
                "#include \"qconv2d.hpp\"\n#include \"qdepthwiseconv2d.hpp\"\n#include \"qpointwiseconv2d.hpp\"\n"
                "#include \"qpad.hpp\"\n#include \"qpool2d.hpp\"\n#include \"qdense.hpp\"\n#include \"qadd.hpp\"\n"
                "#include \"qsoftmax_fixedpoint.hpp\"\n\n"
                f"namespace {self.ns} {{\n\nusing Rq = tinymind::Requantizer<int32_t, int8_t>;\n\n"
                + "".join(self.decls)
                + f"// Activations share one arena, planned from each tensor's lifetime.\n"
                f"constexpr std::size_t kArenaBytes = {arena};\n"
                f"constexpr std::size_t kSteps = {len(self.steps)};\n\n"
                "inline int8_t* arena()\n{\n    alignas(4) static int8_t a[kArenaBytes];\n    return a;\n}\n\n"
                "// step(tag, layer, inputs..., output) runs layer.forward(inputs..., output);\n"
                "// the profiling build passes a step that times each one.\n"
                "template<typename Step>\n"
                "inline void run(Step& step, const int8_t* in, int8_t* out)\n{\n"
                "    int8_t* const a = arena();\n" + calls + "\n}\n\n"
                "struct DirectStep\n{\n"
                "    template<typename Layer, typename... Args>\n"
                "    void operator()(const char*, const Layer& layer, Args... args) const\n    {\n"
                "        layer.forward(args...);\n    }\n};\n\n"
                "inline void forward(const int8_t* in, int8_t* out)\n{\n"
                "    DirectStep step;\n    run(step, in, out);\n}\n\n"
                f"}} // namespace {self.ns}\n"), arena


def flatbuffer_header(var, blob):
    lines = ["    " + ", ".join(str(v) for v in blob[i:i + 20]) + "," for i in range(0, len(blob), 20)]
    return (HDR + "#pragma once\n#include <cstddef>\n\n"
            f"alignas(16) const unsigned char {var}[{len(blob)}] =\n{{\n" + "\n".join(lines) + "\n};\n"
            f"constexpr std::size_t {var}_len = {len(blob)};\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    summary = []
    for name in MODELS:
        blob = fetch(name)
        g = Graph(name, blob)
        ops = g.translate()
        text, arena = g.header()
        up = name.upper()
        with open(os.path.join(OUT, f"mlperf_{name}_tinymind.hpp"), "w") as f:
            f.write(text)
        with open(os.path.join(OUT, f"mlperf_{name}_tflite_int8.h"), "w") as f:
            f.write(flatbuffer_header(f"mlperf_{name}_int8_tflite", blob))

        # Seeded random int8 inputs; the TFLite interpreter's reference kernels
        # give an output hash for the record (TFLM on the board is the check).
        rng = np.random.default_rng(1234 + len(name))
        xs = rng.integers(-128, 128, (N_TEST, g.n_in), dtype=np.int64).astype(np.int8)
        inp = g.it.get_input_details()[0]
        outd = g.it.get_output_details()[0]
        ys = []
        for x in xs:
            g.it.set_tensor(inp["index"], x.reshape(inp["shape"]))
            g.it.invoke()
            ys.append(g.it.get_tensor(outd["index"]).ravel().copy())
        ref_hash = fnv1a(np.array(ys, np.int8).tobytes())
        with open(os.path.join(OUT, f"mlperf_{name}_data.h"), "w") as f:
            f.write(HDR + "// Test inputs: seeded random int8 values, not dataset samples.\n"
                    "#pragma once\n#include <stdint.h>\n\n"
                    f"#define MLPERF_{up}_N_TEST {N_TEST}\n#define MLPERF_{up}_N_IN {g.n_in}\n"
                    f"#define MLPERF_{up}_N_OUT {g.n_out}\n"
                    f"#define MLPERF_{up}_TFLITE_REF_HASH 0x{ref_hash:08X}u\n\n"
                    + c_array("int8_t", f"mlperf_{name}_test_x_i8", xs, align=4))
        produced = set(o for op in g.it._get_ops_details() for o in op["outputs"])
        used = set(i for op in g.it._get_ops_details() for i in op["inputs"] if i >= 0)
        weights = sum(int(np.prod(g.shape(i))) * np.dtype(g.T[i]["dtype"]).itemsize
                      for i in used - produced - {g.in_index} if g.T[i]["dtype"] != np.int32
                      or g.T[i]["quantization_parameters"]["scales"].size)
        summary.append(f"{name}: {len(ops)} ops ({', '.join(sorted(set(ops)))}), {len(g.steps)} tinymind steps, "
                       f"arena {arena} B, const tensors {weights} B, flatbuffer {len(blob)} B, "
                       f"TFLite reference hash 0x{ref_hash:08X}")
    with open(os.path.join(OUT, "summary.txt"), "w") as f:
        f.write("\n".join(summary) + "\n")
    print("\n".join(summary))


