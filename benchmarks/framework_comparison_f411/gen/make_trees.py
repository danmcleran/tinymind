"""Generate the random-forest models for the integer tree comparison.

tinymind (cpp/qtree.hpp) and emlearn (eml_trees.h) both run decision trees
in pure integer arithmetic, so a random forest is the one model both can run
integer-to-integer on an FPU-less part. emlearn has no GBDT and tinymind has
no forest vote helper, so the common model is a scikit-learn
RandomForestClassifier with majority voting:

  tinymind  one tinymind::QDecisionTree per tree over a shared QTreeNode<int8_t>
            pool, leaf_value = the tree's class, majority vote in rf_tinymind.hpp
  emlearn   emlearn.convert(), both its 'inline' (generated if/else code) and
            'loadable' (EmlTrees data + eml_trees_predict) methods

Features are 2 x the digits pixel value (0..32): integers, so the int8 and
int16 inputs are exact, and every split threshold (a midpoint of two training
values) is an integer. That matters for emlearn, which casts thresholds to
int16 and splits on x < t: on raw pixels (thresholds like 3.5 -> 3) it sends
x == 3 the wrong way and loses ~16 points of accuracy. tinymind splits on
x <= floor(t), which is exact for any threshold.

emlearn's x < t still differs from scikit-learn's x <= t when a test value
lands exactly on an (even) threshold, so emlearn agrees with the forest on
slightly fewer test samples. Each backend is therefore checked against its own
host reference: tinymind against the forest's majority vote computed here,
emlearn against emlearn's own compiled C (emlearn.convert(...).predict).

Writes gen/out/rf_data.h, rf_tinymind.hpp, rf_emlearn_inline.h and
rf_emlearn_loadable.h. Requires: scikit-learn, emlearn, numpy.
"""

import os

import emlearn
import numpy as np
import sklearn
from sklearn.datasets import load_digits
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")
HDR = "// Generated by gen/make_trees.py -- do not edit.\n"
N_TREES = 10
MAX_DEPTH = 6
SUBSET = 32  # the test-set prefix the L031 build carries (gen/subset.py)


def fnv1a(data_bytes):
    h = 0x811C9DC5
    for b in data_bytes:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def c_array(ctype, name, values, per_line=16, align=None):
    vals = [str(int(v)) for v in np.asarray(values).flatten()]
    lines = ["    " + ", ".join(vals[i:i + per_line]) + "," for i in range(0, len(vals), per_line)]
    prefix = f"alignas({align}) " if align else ""
    return f"{prefix}const {ctype} {name}[{len(vals)}] =\n{{\n" + "\n".join(lines) + "\n};\n"


def majority(forest, X):
    votes = np.zeros((len(X), forest.n_classes_), np.int64)
    for est in forest.estimators_:
        votes[np.arange(len(X)), est.predict(X).astype(np.int64)] += 1
    return votes.argmax(1)  # ties -> lowest class, as both C implementations do


digits = load_digits()
X = (digits.data * 2).astype(np.int64)
y = digits.target.astype(np.int64)
# Same split as the MLP in make_models.py.
Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, random_state=0, stratify=y)

rf = RandomForestClassifier(n_estimators=N_TREES, max_depth=MAX_DEPTH, random_state=0)
rf.fit(Xtr, ytr)
ref_tm = majority(rf, Xte)

inline = emlearn.convert(rf, method="inline")
loadable = emlearn.convert(rf, method="loadable")
ref_eml = np.asarray(inline.predict(Xte), np.int64)
assert (np.asarray(loadable.predict(Xte)) == ref_eml).all(), "emlearn inline and loadable disagree"
inline.save(file=os.path.join(OUT, "rf_emlearn_inline.h"), name="rf_inline")
loadable.save(file=os.path.join(OUT, "rf_emlearn_loadable.h"), name="rf_loadable")

# tinymind: one flat node pool, each tree's indices local to its own base.
nodes, roots, counts = [], [], []
for est in rf.estimators_:
    t = est.tree_
    roots.append(len(nodes))
    counts.append(t.node_count)
    for i in range(t.node_count):
        if t.children_left[i] == -1:
            nodes.append((-1, 0, -1, -1, int(np.argmax(t.value[i][0]))))
        else:
            th = int(np.floor(t.threshold[i]))
            assert -128 <= th <= 127
            nodes.append((int(t.feature[i]), th, int(t.children_left[i]), int(t.children_right[i]), 0))

tm = [HDR, f"""#pragma once
#include <cstddef>
#include <cstdint>
#include "qtree.hpp"

// scikit-learn RandomForestClassifier, {N_TREES} trees, max_depth {MAX_DEPTH}, on 2 x digits pixels.
// Leaves carry the tree's class; rf::predict() is a majority vote (ties -> lowest class).
namespace tm_rf {{

using Node = tinymind::QTreeNode<int8_t>;
using Tree = tinymind::QDecisionTree<int8_t, int8_t, {max(counts)}, 64>;
constexpr std::size_t NumTrees = {N_TREES};
constexpr std::size_t NumClasses = {rf.n_classes_};

const Node nodes[{len(nodes)}] =
{{
"""]
tm += [f"    {{{f}, {th}, {l}, {r}, {v}}},\n" for f, th, l, r, v in nodes]
tm.append("};\n\nconst Tree trees[NumTrees] =\n{\n")
tm += [f"    {{nodes + {r}}},\n" for r in roots]
tm.append("""};

inline int predict(const int8_t* x)
{
    int32_t votes[NumClasses] = {};
    for (std::size_t t = 0; t < NumTrees; ++t)
    {
        ++votes[trees[t].predict(x)];
    }
    int best = 0;
    for (std::size_t c = 1; c < NumClasses; ++c)
    {
        if (votes[c] > votes[best])
        {
            best = static_cast<int>(c);
        }
    }
    return best;
}

} // namespace tm_rf
""")
open(os.path.join(OUT, "rf_tinymind.hpp"), "w").write("".join(tm))

n = len(Xte)
acc = lambda p: (p == yte).mean()
data = (HDR + "#pragma once\n#include <stdint.h>\n\n"
        f"// sklearn {sklearn.__version__}, emlearn {emlearn.__version__}. Test accuracy: forest predict() {acc(rf.predict(Xte)):.4f}, "
        f"majority vote {acc(ref_tm):.4f}, emlearn {acc(ref_eml):.4f}; emlearn agrees with the vote on "
        f"{int((ref_eml == ref_tm).sum())}/{n}.\n"
        f"// Hashes: FNV-1a over the predicted class of each test sample, whole set and first {SUBSET}.\n"
        f"#define RF_N_TEST {n}\n#define RF_N_IN 64\n#define RF_N_CLASSES {rf.n_classes_}\n"
        f"#define RF_TM_HASH_{n} 0x{fnv1a(ref_tm.astype(np.uint8).tobytes()):08X}u\n"
        f"#define RF_TM_HASH_{SUBSET} 0x{fnv1a(ref_tm[:SUBSET].astype(np.uint8).tobytes()):08X}u\n"
        f"#define RF_EML_HASH_{n} 0x{fnv1a(ref_eml.astype(np.uint8).tobytes()):08X}u\n"
        f"#define RF_EML_HASH_{SUBSET} 0x{fnv1a(ref_eml[:SUBSET].astype(np.uint8).tobytes()):08X}u\n\n"
        + c_array("int8_t", "rf_test_x_i8", Xte.astype(np.int8))
        + c_array("uint8_t", "rf_test_y", yte.astype(np.uint8)))
open(os.path.join(OUT, "rf_data.h"), "w").write(data)

print(f"rf: {len(nodes)} tinymind nodes ({N_TREES} trees, depth {MAX_DEPTH}); vote acc {acc(ref_tm):.4f}, "
      f"emlearn acc {acc(ref_eml):.4f}, agree {int((ref_eml == ref_tm).sum())}/{n}, "
      f"first {SUBSET} agree {int((ref_eml[:SUBSET] == ref_tm[:SUBSET]).sum())}/{SUBSET}")
