namespace
{

// Each layer behind its own noinline call so per-layer timings are not
// polluted by cross-layer inlining and register allocation.
template<typename Layer, typename... Args>
__attribute__((noinline)) void runLayer(const Layer& layer, Args... args)
{
    layer.forward(args...);
}

struct LayerTimer
{
    uint32_t* cycles;
    const char** tags;
    int max;
    int n;

    template<typename Layer, typename... Args>
    void step(const char* tag, const Layer& layer, Args... args)
    {
#if defined(BENCH_SMALL_RAM)
        if (cycles == nullptr)
        {
            runLayer(layer, args...);
            return;
        }
#endif
        const uint32_t a = board_cycles();
        runLayer(layer, args...);
        const uint32_t elapsed = board_cycles() - a;
        if (n < max)
        {
            cycles[n] = elapsed;
            tags[n] = tag;
        }
        ++n;
    }

    // The MLPerf model headers drive their layers through step(tag, layer, ...).
    template<typename Layer, typename... Args>
    void operator()(const char* tag, const Layer& layer, Args... args)
    {
        step(tag, layer, args...);
    }
};

#if defined(MODEL_KWS) && defined(BENCH_SMALL_RAM)

// Boards with little SRAM (the L031 has 8 KB) cannot hold forward()'s
// per-layer statics and a second set for profiling. There the chain
// ping-pongs two buffers, and be_invoke runs this same chain untimed so that
// forward() and its statics are not linked at all.
template<size_t A, size_t B>
constexpr size_t maxOf()
{
    return A > B ? A : B;
}

void kwsChain(LayerTimer& timer)
{
    using namespace tm_kws;
    alignas(4) static int8_t ping[maxOf<maxOf<C1Type::OutputSize, DwType::OutputSize>(), 16>()];
    alignas(4) static int8_t pong[maxOf<P1Type::OutputSize, PwType::OutputSize>()];
    timer.step("conv3x3", C1, gIn, ping);
    timer.step("maxpool", P1, ping, pong);
    timer.step("dwconv3x3", DW, pong, ping);
    timer.step("pwconv", PW, ping, pong);
    timer.step("avgpool", GAP, pong, ping);
    timer.step("fc", D, ping, gOut);
}

#endif

} // namespace

#if defined(MODEL_KWS) && defined(BENCH_SMALL_RAM)
extern "C" __attribute__((noinline)) void be_invoke(void)
{
    LayerTimer timer = {nullptr, nullptr, 0, 0};
    kwsChain(timer);
}
#endif

extern "C" int be_profile(uint32_t* c, const char** t, int max)
{
    LayerTimer timer = {c, t, max, 0};
#if defined(MODEL_MLP)
    using namespace tm_mlp;
    static int8_t a0[32];
    static int8_t a1[16];
    timer.step("fc0", L0, gIn, a0);
    timer.step("fc1", L1, a0, a1);
    timer.step("fc2", L2, a1, gOut);
#elif defined(MLPERF_NS)
    MLPERF_NS::run(timer, gIn, gOut);
#elif defined(BENCH_SMALL_RAM)
    kwsChain(timer);
#else
    using namespace tm_kws;
    static int8_t c1[C1Type::OutputSize];
    static int8_t p1[P1Type::OutputSize];
    static int8_t dw[DwType::OutputSize];
    static int8_t pw[PwType::OutputSize];
    static int8_t gap[16];
    timer.step("conv3x3", C1, gIn, c1);
    timer.step("maxpool", P1, c1, p1);
    timer.step("dwconv3x3", DW, p1, dw);
    timer.step("pwconv", PW, dw, pw);
    timer.step("avgpool", GAP, pw, gap);
    timer.step("fc", D, gap, gOut);
#endif
    return timer.n;
}

#else

extern "C" int be_profile(uint32_t*, const char**, int)
{
    return 0;
}

#endif
