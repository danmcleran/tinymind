int be_argmax(void)
{
    int best = 0;
    for (int k = 1; k < N_OUT; ++k)
    {
        if (gOut[k] > gOut[best])
        {
            best = k;
        }
    }
    return best;
}

uint32_t be_hash(uint32_t h)
{
    for (int k = 0; k < N_OUT; ++k)
    {
        h ^= static_cast<uint8_t>(gOut[k]);
        h *= 0x01000193u;
    }
    return h;
}

