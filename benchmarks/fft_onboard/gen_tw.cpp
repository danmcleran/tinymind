// Host side: writes the Q1.15 twiddle tables for every benchmarked N, built
// by buildQFFTTwiddles, and the output hashes the board must reproduce.
// usage: gen_tw <out.h>
#include "tinymind_platform.hpp"
#include "qcalibration.hpp"

#include "fft_common.hpp"

#include <cstdio>
#include <vector>

namespace
{

template<size_t N>
void emit(FILE* f)
{
    std::vector<int16_t> c(N / 2);
    std::vector<int16_t> s(N / 2);
    tinymind::buildQFFTTwiddles(N, c.data(), s.data());

    std::fprintf(f, "#if MAXN >= %zu\nTW_STORAGE int16_t tw_cos_%zu[%zu] = {", N, N, N / 2);
    for (size_t i = 0; i < N / 2; ++i)
    {
        std::fprintf(f, "%s%d", i ? "," : "", c[i]);
    }
    std::fprintf(f, "};\nTW_STORAGE int16_t tw_sin_%zu[%zu] = {", N, N / 2);
    for (size_t i = 0; i < N / 2; ++i)
    {
        std::fprintf(f, "%s%d", i ? "," : "", s[i]);
    }
    std::fprintf(f, "};\n#endif\n");

    tinymind::QFFT1D<N> qfft;
    qfft.twiddle_cos = c.data();
    qfft.twiddle_sin = s.data();
    tinymind::QRFFT1D<N> qrfft;
    qrfft.twiddle_cos = c.data();
    qrfft.twiddle_sin = s.data();
    std::vector<int16_t> in(N);
    std::vector<int16_t> re(N);
    std::vector<int16_t> im(N);
    uint32_t hq = 0;
    uint32_t hr = 0;
    fftbench::hashBoth<N>(qfft, qrfft, in.data(), re.data(), im.data(), &hq, &hr);
    std::fprintf(f, "#define HASH_QFFT_%zu 0x%08Xu\n#define HASH_QRFFT_%zu 0x%08Xu\n", N, hq, N, hr);
}

} // namespace

int main(int argc, char** argv)
{
    if (argc != 2)
    {
        std::fprintf(stderr, "usage: %s <out.h>\n", argv[0]);
        return 2;
    }
    FILE* f = std::fopen(argv[1], "w");
    if (!f)
    {
        return 1;
    }
    std::fprintf(f, "// Generated by gen_tw.cpp; do not edit.\n#pragma once\n#include <stdint.h>\n");
    std::fprintf(f, "#ifndef MAXN\n#error define MAXN before including tw.h\n#endif\n#ifdef TW_IN_RAM\n#define TW_STORAGE static\n#else\n#define TW_STORAGE static const\n#endif\n");
    emit<64>(f);
    emit<128>(f);
    emit<256>(f);
    emit<512>(f);
    emit<1024>(f);
    return std::fclose(f) == 0 ? 0 : 1;
}
