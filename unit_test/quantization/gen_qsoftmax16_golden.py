"""Golden rows for QSoftmaxInt16 from TFLite itself.

Converts a Keras softmax with TFLite's 16x8 scheme
(EXPERIMENTAL_TFLITE_BUILTINS_ACTIVATIONS_INT16_WEIGHTS_INT8, int16 input and
output), runs it in TFLite's interpreter with the reference kernels, and
writes qsoftmax16_tflite_golden.hpp: for each case the softmax input's
float32 scale and rows of int16 inputs with TFLite's int16 outputs.

Needs tensorflow (CPU) in a venv, never the system Python; not run in CI:

    python3 -m venv /tmp/tfvenv && /tmp/tfvenv/bin/pip install tensorflow-cpu numpy
    /tmp/tfvenv/bin/python gen_qsoftmax16_golden.py qsoftmax16_tflite_golden.hpp
"""

import itertools
import sys

import numpy as np
import tensorflow as tf

# (features, spread of the calibration logits, rows kept)
# This file's own license comment, repeated in the generated header.
with open(__file__) as _source:
    LICENSE = "".join(itertools.takewhile(lambda line: line.startswith("#"), _source))

CASES = ((3, 1.0, 20), (10, 4.0, 20), (10, 20.0, 20), (64, 8.0, 20), (257, 6.0, 2))
SPECIAL = (-32768, 32767, 0, -1, 1, 12345, -12345, 7, -32767, 100)


def tflite_rows(features, spread, count, rng):
    inp = tf.keras.Input(shape=(features,))
    model = tf.keras.Model(inp, tf.keras.layers.Softmax()(inp * 1.0))

    def representative():
        for _ in range(200):
            yield [rng.normal(0, spread, (1, features)).astype(np.float32)]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = representative
    conv.target_spec.supported_ops = [tf.lite.OpsSet.EXPERIMENTAL_TFLITE_BUILTINS_ACTIVATIONS_INT16_WEIGHTS_INT8]
    conv.inference_input_type = tf.int16
    conv.inference_output_type = tf.int16
    it = tf.lite.Interpreter(model_content=conv.convert(),
                             experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_REF)
    it.allocate_tensors()
    ops = [o["op_name"] for o in it._get_ops_details()]
    assert ops == ["SOFTMAX"], ops
    i_d, o_d = it.get_input_details()[0], it.get_output_details()[0]
    scale, zp = i_d["quantization"]
    assert zp == 0 and o_d["quantization"] == (1.0 / 32768.0, 0)
    rows = []
    for k in range(count):
        if k < min(count, len(SPECIAL)):
            # Uniform rows, then rows with one class at the top of the range.
            x = np.full(features, SPECIAL[k], dtype=np.int16)
            if k >= 5:
                x[k % features] = 32767
        else:
            x = rng.integers(-32768, 32768, features).astype(np.int16)
            if k % 3 == 0:
                x = (x // (1 + k % 97)).astype(np.int16)
        it.set_tensor(i_d["index"], x.reshape(1, features))
        it.invoke()
        rows.append((x, it.get_tensor(o_d["index"]).reshape(-1)))
    return np.float32(scale), rows


def main(path):
    rng = np.random.default_rng(7)
    license = [line[2:] if line.startswith("# ") else line[1:] for line in LICENSE.strip().splitlines()]
    out = ["/**"] + ["* " + line if line else "*" for line in license] + ["*/", "",
           "// Generated by gen_qsoftmax16_golden.py from TFLite " + tf.__version__ + "'s int16 SOFTMAX",
           "// (reference kernels). Do not edit.", "", "#pragma once", "", "#include <cstddef>", "#include <cstdint>",
           "", "namespace qsoftmax16_golden", "{"]
    names = []
    for n, (features, spread, count) in enumerate(CASES):
        scale, rows = tflite_rows(features, spread, count, rng)
        name = f"kCase{n}"
        names.append((name, features, count))
        out.append(f"    // features {features}, input scale {float(scale)!r}")
        out.append(f"    constexpr uint32_t {name}ScaleBits = 0x{int(scale.view(np.uint32)):08X}u;")
        for kind, idx in (("Input", 0), ("Output", 1)):
            out.append(f"    constexpr int16_t {name}{kind}[{features * count}] = {{")
            for x in rows:
                values = [str(int(v)) for v in x[idx]]
                for start in range(0, len(values), 16):
                    out.append("        " + ", ".join(values[start:start + 16]) + ",")
            out.append("    };")
    out.append("}")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    for name, features, count in names:
        print(f"{name}: {features} features, {count} rows")


if __name__ == "__main__":
    main(sys.argv[1])
